export type TranslationScope = keyof typeof translations
export type TextValues = Readonly<Record<string, string | number>>

/** Typed keys; interpolate whole phrases so each language controls word order. */
export function translator<S extends TranslationScope>(language: Language, scope: S) {
  return (key: keyof (typeof translations)[S], values: TextValues = {}): string => {
    const pair = translations[scope][key] as [string, string]
    return pair[language === 'th' ? 1 : 0].replace(/\{(\w+)\}/g, (token, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : token)
  }
}
